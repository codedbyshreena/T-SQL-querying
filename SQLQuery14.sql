--20. List all departments who have no person. 
SELECT D.DEPARTMENTNAME, P.PERSONNAME
FROM DEPARTMENT D
LEFT JOIN PERSON P
ON D.DEPARTMENTID = P.DEPARTMENTID
WHERE P.DEPARTMENTID IS NULL

--21. List out department names in which more than two persons are working. 
SELECT D.DEPARTMENTNAME, COUNT(P.DEPARTMENTID) AS No_Of_Employees
FROM DEPARTMENT D
JOIN PERSON P
ON D.DEPARTMENTID = P.DEPARTMENTID
GROUP BY D.DEPARTMENTNAME, D.DEPARTMENTID
HAVING COUNT(P.DEPARTMENTID) > 2

--22. Give a 10% increment in the computer department employee’s salary. (Use Update)
UPDATE EMPLOYEE
SET SALARY = SALARY + (SALARY * 0.10)
WHERE DEPARTMENT IN (
    SELECT DepartmentID
    FROM DEPARTMENT
    WHERE DepartmentName = 'COMPUTER'
)