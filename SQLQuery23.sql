--1. INSERT Procedures: Create stored procedures to insert records into STUDENT tables 
--(PR_INSERT_STUDENT) 
GO

CREATE PROCEDURE PR_INSERT_STUDENT
    @STDID INT,
    @SNAME VARCHAR(50),
    @CITY VARCHAR(50),
    @SPI DECIMAL(4,2),
    @BRANCH VARCHAR(50)
AS
BEGIN
    INSERT INTO STUDENT VALUES 
    (@STDID, @SNAME, @CITY, @SPI, @BRANCH);
END;


